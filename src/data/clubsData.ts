export function generateFullClubDatabase(): { clubs: Club[]; owners: Owner[]; managers: Manager[]; freeAgents: Player[] } {
  const ownersMap = new Map<string, Owner>();
  RAW_OWNERS_DATA.forEach(o => ownersMap.set(o.id, o));

  const managersMap = new Map<string, Manager>();
  RAW_MANAGERS_DATA.forEach(m => {
    if (m.clubId) managersMap.set(m.clubId, m);
  });

  const clubs: Club[] = RAW_CLUBS_DATA.map((rawClub, clubIdx) => {
    // Generate full squad of 20 players based on club tier
    const squad: Player[] = [];
    
    // Add curated key players first
    rawClub.keyPlayers.forEach((kp, kpIdx) => {
      squad.push({
        id: `p_${rawClub.id}_${kpIdx}`,
        name: kp.name,
        nationality: 'England',
        age: kp.age,
        position: kp.pos,
        roleDetail: kp.role,
        overall: kp.ovr,
        growthMomentum: kp.age <= 23 ? 'breakout' : kp.age <= 28 ? 'steady' : 'prime',
        value: kp.val,
        wage: kp.wage,
        contractYears: 2 + (kpIdx % 3),
        form: 7.0 + ((kpIdx % 5) * 0.2),
        happiness: 80,
        morale: 'happy',
        goals: kp.pos === 'FWD' ? 6 : kp.pos === 'MID' ? 2 : 0,
        assists: kp.pos === 'MID' ? 4 : kp.pos === 'DEF' ? 1 : 0,
        appearances: 12,
        cleanSheets: kp.pos === 'GK' || kp.pos === 'DEF' ? 4 : 0,
        clubId: rawClub.id,
      });
    });

    // Fill remaining squad positions up to 20 players
    const positionsNeeded: Player['position'][] = [
      'GK', 'DEF', 'DEF', 'DEF', 'DEF', 'MID', 'MID', 'MID', 'MID', 'FWD', 'FWD', 'DEF', 'MID', 'FWD',
    ];

    const baseOvr = rawClub.tier === 1 ? 79 : rawClub.tier === 2 ? 72 : 66;

    positionsNeeded.slice(0, 20 - squad.length).forEach((pos, idx) => {
      const fName = FIRST_NAMES[(clubIdx * 7 + idx) % FIRST_NAMES.length];
      const lName = LAST_NAMES[(clubIdx * 5 + idx * 3) % LAST_NAMES.length];
      const isYoung = idx % 2 === 0;
      const age = isYoung ? 19 + (idx % 4) : 25 + (idx % 7);
      const ovr = Math.max(50, Math.min(92, baseOvr - 2 + (idx % 5) - (isYoung ? 3 : 0)));
      const roleList = ROLES_BY_POS[pos];
      const role = roleList[idx % roleList.length];
      const valMultiplier = rawClub.tier === 1 ? 1200000 : rawClub.tier === 2 ? 300000 : 70000;
      const val = Math.round(ovr * ovr * valMultiplier * 0.003);
      const wageMultiplier = rawClub.tier === 1 ? 1500 : rawClub.tier === 2 ? 400 : 120;
      const wage = Math.round(ovr * wageMultiplier);

      squad.push({
        id: `p_${rawClub.id}_fill_${idx}`,
        name: `${fName} ${lName}`,
        nationality: idx % 3 === 0 ? 'England' : idx % 5 === 0 ? 'Scotland' : 'Ireland',
        age,
        position: pos,
        roleDetail: role,
        overall: ovr,
        growthMomentum: isYoung ? 'rapid' : 'steady',
        value: val,
        wage,
        contractYears: 1 + (idx % 4),
        form: 6.8 + (idx % 4) * 0.2,
        happiness: 75,
        morale: 'content',
        goals: pos === 'FWD' ? 2 : 0,
        assists: pos === 'MID' ? 2 : 0,
        appearances: 8,
        cleanSheets: pos === 'GK' || pos === 'DEF' ? 2 : 0,
        clubId: rawClub.id,
      });
    });

    // Check or create owner
    let ownerId = `owner_${rawClub.id}`;
    if (!ownersMap.has(ownerId)) {
      const genericOwner: Owner = {
        id: ownerId,
        name: `${rawClub.name} Board of Directors`,
        nationality: 'British',
        wealth: rawClub.tier === 1 ? 'moderate' : rawClub.tier === 2 ? 'moderate' : 'frugal',
        patience: 'balanced',
        involvement: 'collaborative',
        recruitmentPhilosophy: rawClub.tier === 1 ? 'marquee_stars' : 'youth_development',
        approval: 70,
        takeoverRisk: 20,
        description: `Custodial leadership for ${rawClub.name}. Prioritizes steady progress and sustainable financial management.`,
      };
      ownersMap.set(ownerId, genericOwner);
    }

    // Check or create manager
    let managerId: string | null = null;
    if (managersMap.has(rawClub.id)) {
      managerId = managersMap.get(rawClub.id)!.id;
    } else {
      const genericMgrId = `mgr_${rawClub.id}`;
      const managerName = `${FIRST_NAMES[(clubIdx * 3) % FIRST_NAMES.length]} ${LAST_NAMES[(clubIdx * 4) % LAST_NAMES.length]}`;
      const genMgr: Manager = {
        id: genericMgrId,
        name: managerName,
        nationality: 'British',
        age: 44 + (clubIdx % 15),
        tacticalStyle: clubIdx % 2 === 0 ? 'High Gegenpress' : 'Direct Counter-Attack',
        preferredFormation: '4-3-3 Holding',
        controlDesire: clubIdx % 3 === 0 ? 'autocrat' : clubIdx % 3 === 1 ? 'collaborator' : 'head_coach',
        reputation: rawClub.tier === 1 ? 80 : rawClub.tier === 2 ? 72 : 65,
        trustInDirector: 75,
        wage: rawClub.tier === 1 ? 75000 : rawClub.tier === 2 ? 25000 : 10000,
        contractYears: 2,
        clubId: rawClub.id,
        profileSnippet: `Experienced Football League tactician managing ${rawClub.name}. Focused on collective work-rate and team structure.`,
      };
      managersMap.set(rawClub.id, genMgr);
      managerId = genericMgrId;
    }

    // Generate initial 5 youth academy prospects (ages 15-18)
    const traitsList: ProspectTrait[] = [
      'Generational Prodigy', 'Driven Workhorse', 'Raw Diamond', 'Technical Magician', 'Natural Leader', 'Late Bloomer', 'Relentless Engine'
    ];
    const academyPositions: Player['position'][] = ['GK', 'DEF', 'DEF', 'MID', 'FWD'];
    const academy: AcademyPlayer[] = academyPositions.map((pos, aIdx) => {
      const fName = FIRST_NAMES[(clubIdx * 11 + aIdx * 7) % FIRST_NAMES.length];
      const lName = LAST_NAMES[(clubIdx * 13 + aIdx * 5) % LAST_NAMES.length];
      const trait = traitsList[(clubIdx * 3 + aIdx) % traitsList.length];
      const age = 15 + ((clubIdx + aIdx) % 4); // 15 to 18
      const roleList = ROLES_BY_POS[pos];
      const roleDetail = roleList[aIdx % roleList.length];
      const baseOvr = rawClub.tier === 1 ? 55 : rawClub.tier === 2 ? 50 : 46;
      const overall = Math.max(45, Math.min(68, baseOvr + (aIdx % 7) - 2));
      const momentumTier: MomentumTier = trait === 'Generational Prodigy' 
        ? 'Generational Prodigy' 
        : trait === 'Late Bloomer' 
        ? 'Late Surge' 
        : (aIdx % 2 === 0 ? 'High Tempo' : 'Steady Climber');

      return {
        id: `acad_${rawClub.id}_init_${aIdx}`,
        name: `${fName} ${lName}`,
        nationality: aIdx % 3 === 0 ? 'England' : aIdx % 5 === 0 ? 'Scotland' : 'Wales',
        age,
        position: pos,
        roleDetail,
        overall,
        momentumTier,
        trait,
        scoutReport: trait === 'Generational Prodigy' 
          ? 'Exceptional technical vision and quick decision making. Accelerating momentum with potential to reach 99.'
          : trait === 'Driven Workhorse'
          ? 'Outstanding determination and tactical compliance. Relentless training habits driving rapid progress.'
          : trait === 'Raw Diamond'
          ? 'Explosive athletic foundation with raw decision-making. High growth rate with senior guidance.'
          : 'Consistent academy performer demonstrating solid positional awareness and steady developmental pace.',
        graduatingSeason: 2026,
      };
    });

    return {
      id: rawClub.id,
      name: rawClub.name,
      shortName: rawClub.shortName,
      tier: rawClub.tier,
      primaryColor: rawClub.primaryColor,
      secondaryColor: rawClub.secondaryColor,
      stadium: rawClub.stadium,
      capacity: rawClub.capacity,
      balance: rawClub.balance,
      transferBudget: rawClub.transferBudget,
      wageBudget: rawClub.wageBudget,
      ownerId,
      managerId,
      squad,
      academy,
      played: 0,
      won: 0,
      drawn: 0,
      lost: 0,
      goalsFor: 0,
      goalsAgainst: 0,
      goalDifference: 0,
      points: 0,
      form: [],
      prestige: rawClub.prestige,
      fanExpectation: rawClub.fanExpectation,
    };
  });

  return {
    clubs,
    owners: Array.from(ownersMap.values()),
    managers: [...Array.from(managersMap.values()), ...RAW_MANAGERS_DATA.filter(m => m.clubId === null)],
    freeAgents: FREE_AGENT_PLAYERS,
  };
}
